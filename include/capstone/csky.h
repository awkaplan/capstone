/// Operand type for instruction's operands
typedef enum csky_op_type {
	CSKY_OP_INVALID = CS_OP_INVALID, ///< Invalid
	CSKY_OP_REG = CS_OP_REG, ///< Register operand
	CSKY_OP_IMM = CS_OP_IMM, ///< Immediate operand
	CSKY_OP_MEM = CS_OP_MEM, ///< Memory operand
} csky_op_type;

/// Instruction's operand referring to memory
/// This is associated with CSKY_OP_MEM operand type above
typedef struct csky_op_mem {
	unsigned int base; ///< base register
	unsigned int index; ///< index register
	int64_t disp; ///< displacement/offset value
} csky_op_mem;

/// Instruction operand
typedef struct cs_csky_op {
	csky_op_type type; ///< operand type
	union {
		unsigned int reg; ///< register value for REG operand
		int64_t imm; ///< immediate value for IMM operand
		csky_op_mem mem; ///< base/disp value for MEM operand
	};

	/// How is this operand accessed? (READ, WRITE or READ|WRITE)
	/// NOTE: this field is irrelevant if engine is compiled in DIET mode.
	cs_ac_type access;
} cs_csky_op;

#define NUM_CSKY_OPS 16

/// Instruction structure
typedef struct cs_csky {
	/// Number of operands of this instruction,
	/// or 0 when instruction has no operand.
	uint8_t op_count;
	cs_csky_op operands[NUM_CSKY_OPS]; ///< operands for this instruction.
} cs_csky;

